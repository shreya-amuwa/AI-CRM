import { degrees, PDFDocument, rgb, StandardFonts } from 'pdf-lib';

/** The values printed on a payout slip (payout_slip_data, migration 20270123000100). */
export interface PayoutSlipData {
  slipNo: string; name: string; employeeCode: string | null; department: string | null;
  amount: number; tdsAmount: number; netAmount: number; reference: string | null; paidOn: string | null;
  channel: 'MANUAL' | 'RAZORPAY' | null;
  method: { kind?: string; holderName?: string; accountNumber?: string | null; ifsc?: string | null; upiId?: string | null; otherDetails?: string | null } | null;
  finalSettlement: boolean; void: boolean;
}

// Helvetica (a standard PDF font) has no rupee sign, so amounts read "Rs. 1,234.50".
const rs = (n: number) => `Rs. ${Number(n).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
const day = (iso: string | null) => (iso ? new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }) : '-');
// keep only characters the standard font can draw
const safe = (s: string | null | undefined) => (s ?? '-').replace(/[^\x20-\x7E]/g, '').trim() || '-';

function methodText(m: PayoutSlipData['method']): string {
  if (!m) return '-';
  if (m.kind === 'BANK') return `Bank account ${safe(m.accountNumber?.replace(/•/g, 'x'))}, IFSC ${safe(m.ifsc)}`;
  if (m.kind === 'UPI') return `UPI ${safe(m.upiId?.replace(/•/g, 'x'))}`;
  return 'International bank transfer';
}

/** An A4 payout slip: who was paid, gross, TDS and net, how and when. A reversed payout is printed VOID. */
export async function renderPayoutSlip(d: PayoutSlipData): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Payout slip ${d.slipNo}`);
  const page = doc.addPage([595.28, 841.89]);
  const regular = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.1, 0.12, 0.16), grey = rgb(0.4, 0.43, 0.48), line = rgb(0.85, 0.87, 0.9);
  let y = 780;
  page.drawText('Amuwa Corporation', { x: 50, y, size: 18, font: bold, color: ink });
  y -= 22;
  page.drawText(d.finalSettlement ? 'Incentive payout slip - final settlement' : 'Incentive payout slip', { x: 50, y, size: 12, font: regular, color: grey });
  page.drawText(`Slip no. ${safe(d.slipNo)}`, { x: 400, y: 780, size: 10, font: bold, color: ink });
  y -= 18;
  page.drawLine({ start: { x: 50, y }, end: { x: 545, y }, thickness: 1, color: line });
  y -= 30;
  const row = (label: string, value: string, strong = false) => {
    page.drawText(label, { x: 50, y, size: 10, font: regular, color: grey });
    page.drawText(value, { x: 220, y, size: strong ? 12 : 10, font: strong ? bold : regular, color: ink, maxWidth: 325 });
    y -= strong ? 24 : 20;
  };
  row('Paid to', safe(d.name));
  if (d.employeeCode) row('Employee code', safe(d.employeeCode));
  row('Department', safe(d.department));
  row('Paid on', day(d.paidOn));
  row('Paid by', d.channel === 'RAZORPAY' ? 'Razorpay payout' : 'Bank / UPI transfer by Accounts');
  row('Sent to', methodText(d.method));
  row('Reference', safe(d.reference));
  y -= 10;
  page.drawLine({ start: { x: 50, y: y + 8 }, end: { x: 545, y: y + 8 }, thickness: 1, color: line });
  y -= 10;
  row('Amount withdrawn', rs(d.amount));
  row('TDS deducted', rs(d.tdsAmount));
  row('Net paid', rs(d.netAmount), true);
  y -= 20;
  page.drawText('Sales incentives earned in the CRM and withdrawn through Accounts.', { x: 50, y, size: 9, font: regular, color: grey });
  page.drawText('This slip is generated by the CRM and needs no signature.', { x: 50, y: y - 14, size: 9, font: regular, color: grey });
  if (d.void) {
    page.drawText('VOID', { x: 170, y: 380, size: 120, font: bold, color: rgb(0.86, 0.15, 0.15), opacity: 0.25, rotate: degrees(35) });
    page.drawText('This payout was reversed by the bank: the amount went back to the balance.', { x: 50, y: 120, size: 10, font: bold, color: rgb(0.7, 0.1, 0.1) });
  }
  return doc.save();
}
