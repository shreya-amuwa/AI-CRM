// Builds server/hrDocuments/templateAssets.ts from the two official templates (run by hand when a template changes):
//   node scripts/prepare-hr-templates.mjs <NDA.pdf> <experience-letter.pdf>
// The templates' artwork, fonts and legal wording are kept untouched. Only the SAMPLE values are removed from the page content
// (not painted over, so they cannot be copied out of a finished document): on the NDA the date and the employee's name line, on the
// Experience Letter the sample body. The server draws the real values in their place (server/hrDocuments/render.ts).
import { PDFDocument, PDFName, PDFArray, PDFRawStream, decodePDFRawStream } from 'pdf-lib';
import fs from 'node:fs';

const [, , ndaPath, expPath] = process.argv;
if (!ndaPath || !expPath) { console.error('usage: node scripts/prepare-hr-templates.mjs <NDA.pdf> <experience.pdf>'); process.exit(1); }

const BLOCK = /BT[\s\S]*?ET/g;
const pos = b => { const m = /([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) Tm/.exec(b) || /([-\d.]+) ([-\d.]+) Td/.exec(b); return m ? [+m[m.length - 2], +m[m.length - 1]] : null; };

/** Removes every text object of one page for which drop(x, y) is true. Returns how many were removed. */
async function strip(doc, pageNo, drop) {
  const page = doc.getPage(pageNo - 1);
  const contents = page.node.Contents();
  const refs = contents instanceof PDFArray ? contents.asArray() : [page.node.get(PDFName.of('Contents'))];
  let removed = 0;
  for (const ref of refs) {
    const stream = doc.context.lookup(ref);
    const text = Buffer.from(decodePDFRawStream(stream).decode()).toString('latin1');
    const out = text.replace(BLOCK, b => { const p = pos(b); if (p && drop(p[0], p[1])) { removed++; return ''; } return b; });
    if (out !== text) {
      const fresh = doc.context.flateStream(Buffer.from(out, 'latin1'));
      doc.context.assign(ref, fresh);
    }
  }
  return removed;
}
function clean(doc, title) {
  doc.catalog.delete(PDFName.of('Metadata'));
  doc.setTitle(title); doc.setAuthor('Amuwa Corporation'); doc.setSubject(''); doc.setKeywords([]);
  doc.setCreator('Amuwa Corporation'); doc.setProducer('Amuwa Corporation');
}
const near = (a, b) => Math.abs(a - b) < 0.5;

const nda = await PDFDocument.load(fs.readFileSync(ndaPath));
const dateGone = await strip(nda, 1, (x, y) => near(y, 653.5) && x > 470);      // "Date: 11-09-2026"
const nameGone = await strip(nda, 5, (x, y) => near(y, 582.43));                // "I, <name> acknowledge and accept ... herein."
if (dateGone !== 8 || nameGone !== 35) console.warn(`unexpected NDA block counts: date ${dateGone}, line ${nameGone}`);
clean(nda, 'Non-Disclosure Agreement');

const exp = await PDFDocument.load(fs.readFileSync(expPath));
const bodyGone = await strip(exp, 1, (x, y) => y > 385 && y < 650);            // Date ... "Amuwa Corporation" signature (keeps the title, toll-free line, header, footer)
clean(exp, 'Experience Letter');
console.log({ dateGone, nameGone, bodyGone });

const b64 = async d => Buffer.from(await d.save({ useObjectStreams: false })).toString('base64');
const wrap = s => s.match(/.{1,120}/g).join("'\n  + '");
fs.writeFileSync(new URL('../server/hrDocuments/templateAssets.ts', import.meta.url),
`/**
 * GENERATED by scripts/prepare-hr-templates.mjs - do not edit by hand.
 * The official Amuwa NDA and Experience Letter, with the sample values removed (see the script). Kept inline so the serverless
 * function needs no file access (the same reason the invoice stationery in server/invoices/assets.ts is inline).
 */
export const NDA_TEMPLATE_BASE64 =
  '${wrap(await b64(nda))}';

export const EXPERIENCE_TEMPLATE_BASE64 =
  '${wrap(await b64(exp))}';
`);
