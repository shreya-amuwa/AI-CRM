// Builds server/hrDocuments/offerTemplateAsset.ts from the official Offer Letter (run by hand when the template changes):
//   soffice --headless --convert-to pdf <Offer_Letter.docx>          (LibreOffice, as for the Experience Letter)
//   node scripts/prepare-hr-offer-template.mjs <Offer_Letter.pdf>
// The letterhead of page 1 is kept untouched (logo, contacts, partner badges, the toll-free line, the footer addresses and artwork). Only the
// SAMPLE letter is removed from the page content (not painted over, so it cannot be copied out of a finished document): every text object of
// the body (between the header and the toll-free line) and the page number. The server draws the real letter in that area on as many copies
// of this page as the letter needs, with its own "n/N" page numbers (server/hrDocuments/offer.ts).
import { PDFDocument, PDFName, PDFArray, decodePDFRawStream } from 'pdf-lib';
import fs from 'node:fs';

const [, , offerPath] = process.argv;
if (!offerPath) { console.error('usage: node scripts/prepare-hr-offer-template.mjs <Offer_Letter.pdf>'); process.exit(1); }

const BLOCK = /BT[\s\S]*?ET/g;
const pos = b => { const m = /([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+) Tm/.exec(b) || /([-\d.]+) ([-\d.]+) Td/.exec(b); return m ? [+m[m.length - 2], +m[m.length - 1]] : null; };

async function strip(doc, pageNo, drop) {
  const page = doc.getPage(pageNo - 1);
  const contents = page.node.Contents();
  const refs = contents instanceof PDFArray ? contents.asArray() : [page.node.get(PDFName.of('Contents'))];
  let removed = 0;
  for (const ref of refs) {
    const stream = doc.context.lookup(ref);
    const text = Buffer.from(decodePDFRawStream(stream).decode()).toString('latin1');
    // text objects, and the small images placed in the body (the list bullets: "q 7.9 0 0 7.9 x y cm /ImN Do Q")
    const out = text
      .replace(BLOCK, b => { const p = pos(b); if (p && drop(p[0], p[1])) { removed++; return ''; } return b; })
      .replace(/q ([\d.]+) 0 0 ([\d.]+) ([-\d.]+) ([-\d.]+) cm\s*\/Im\d+ Do Q/g, (all, w, h, x, y) => {
        if (+w < 12 && +h < 12 && drop(+x, +y)) { removed++; return ''; }
        return all;
      });
    if (out !== text) doc.context.assign(ref, doc.context.flateStream(Buffer.from(out, 'latin1')));
  }
  return removed;
}

const src = await PDFDocument.load(fs.readFileSync(offerPath));
const H = src.getPage(0).getHeight();
// the body (text and list bullets): from under the header (150pt from the top) down to above the toll-free line (630pt from the top); and the page number "1/2"
const bodyGone = await strip(src, 1, (x, y) => (y > H - 630 && y < H - 150) || (y < 20 && x > 540));
const out = await PDFDocument.create();
const [page] = await out.copyPages(src, [0]);
out.addPage(page);
out.setTitle('Offer Letter'); out.setAuthor('Amuwa Corporation'); out.setCreator('Amuwa Corporation'); out.setProducer('Amuwa Corporation');
console.log({ bodyGone, pages: out.getPageCount() });

const b64 = Buffer.from(await out.save({ useObjectStreams: false })).toString('base64');
fs.writeFileSync(new URL('../server/hrDocuments/offerTemplateAsset.ts', import.meta.url),
`/**
 * GENERATED by scripts/prepare-hr-offer-template.mjs - do not edit by hand.
 * Page 1 of the official Amuwa Offer Letter (the letterhead), with the sample letter removed. Kept inline so the serverless function needs no
 * file access. ONE string literal on purpose (see templateAssets.ts).
 */
export const OFFER_TEMPLATE_BASE64 =
  '${b64}';
`);
