\set ON_ERROR_STOP 1
begin;
reset role;
create temp table cp(k text primary key,v uuid);
grant all on cp to authenticated,service_role;
insert into auth.users(email,email_confirmed_at,raw_user_meta_data) values
 ('career.one@example.com',now(),'{"candidate_portal":true}'),('career.two@example.com',now(),'{"candidate_portal":true}'),('career.unverified@example.com',null,'{"candidate_portal":true}');
set constraints all immediate;
insert into cp select 'one',id from auth.users where email='career.one@example.com';
insert into cp select 'two',id from auth.users where email='career.two@example.com';
insert into cp select 'unverified',id from auth.users where email='career.unverified@example.com';
select test.check(not exists(select 1 from profiles where id in(select v from cp)),'candidate signup creates no staff profiles or employee approval requests');
select test.login('hr_head');
select hr_career_posting(jsonb_build_object('position_id',(select id from hr_positions where title='Backend Developer'),'title','Portal Developer','description','Build reliable applications with our engineering team.','location','Mumbai','employment_type','FULL_TIME','published',true));
reset role;
insert into cp select 'job',id from career_postings where title='Portal Developer';
set role anon;
select test.check(career_jobs()->>'total'='1','public sees the published job');
select test.must_fail($$select * from career_applicants$$,'anonymous cannot read candidate data','permission denied');
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select v from cp where k='unverified'),'role','authenticated')::text,true);
set role authenticated;
select test.must_fail($$select career_profile()$$,'email verification is required','Verify your email');
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select v from cp where k='one'),'role','authenticated')::text,true);
set role authenticated;
select test.check(career_profile()->>'name'='','empty candidate profile is real, not seeded');
select career_profile('{"name":"Portal Candidate","phone":"9847650321","city":"Mumbai","state":"Maharashtra","education":"Graduate","experience":"Fresher","skills":"TypeScript","bio":"","version":1}');
select test.must_fail($$select career_profile('{"name":"Conflict","phone":"9847650321","version":1}')$$,'stale edits cannot overwrite profile','CONFLICT');
insert into cp select 'file',(career_file(null,'{"file_name":"resume.pdf","size_bytes":10,"storage_provider":"SUPABASE"}')->>'id')::uuid;
select test.must_fail($$select career_file((select v from cp where k='file'),'{"action":"COMPLETE","size_bytes":10}')$$,'browser cannot attest upload content verification','FORBIDDEN');
select test.must_fail($$select career_apply((select v from cp where k='job'),(select v from cp where k='file'))$$,'unfinished resumes cannot be submitted','uploaded resume');
reset role;
set role service_role;
select career_file_verified((select v from cp where k='file'),10,(select v::text from cp where k='one')||'/sealed/test.pdf');
reset role;
set role authenticated;
insert into cp select 'app',(career_apply((select v from cp where k='job'),(select v from cp where k='file'))->>'id')::uuid;
select test.check((career_apply((select v from cp where k='job'),(select v from cp where k='file'))->>'id')::uuid=(select v from cp where k='app'),'duplicate submission returns the same application');
select career_profile('{"name":"New Profile Name","phone":"9847650321","city":"Pune","state":"Maharashtra","education":"Graduate","experience":"Fresher","skills":"TypeScript","bio":"","version":2}');
select test.check(career_applications()->0#>>'{snapshot,profile,name}'='Portal Candidate','submitted profile snapshot is immutable');
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select v from cp where k='two'),'role','authenticated')::text,true);
set role authenticated;
select test.check(jsonb_array_length(career_applications())=0,'another candidate cannot see the application');
select test.must_fail($$select career_file((select v from cp where k='file'))$$,'another candidate cannot read the resume','NOT_FOUND');
select test.must_fail($$select hr_career_posting()$$,'candidate cannot manage jobs','FORBIDDEN');
select test.must_fail($$select career_file_verified((select v from cp where k='file'),10,(select v::text from cp where k='one')||'/sealed/test.pdf')$$,'candidate cannot bypass upload verification','permission denied');
select test.login('tm_a');
select test.must_fail($$select career_profile()$$,'ordinary staff cannot enter candidate membership implicitly','not registered');
select test.must_fail($$select hr_career_posting()$$,'another department cannot manage recruitment jobs','FORBIDDEN');
reset role;
select test.check((select count(*)=1 from career_applications),'only one application exists');
select test.check(exists(select 1 from hr_candidates where email='career.one@example.com'),'application feeds existing HR recruitment');
select test.check(exists(select 1 from audit_logs where action='CANDIDATE_PROFILE_UPDATED' and metadata->>'actor_auth_id'=(select v::text from cp where k='one')),'candidate audit identifies the authenticated actor');
-- Assessment and progression checks share the isolated application fixture.
select test.login('hr_head');
set role authenticated;
insert into cp select 'test',(hr_career_tests('{"title":"Portal MCQ","duration_minutes":10,"pass_percent":100,"questions":[{"prompt":"Choose two","options":["one","two"],"correct":1}]}')->0->>'id')::uuid;
insert into cp select 'attempt',(hr_career_invite((select v from cp where k='app'),(select v from cp where k='test'),now()+interval '1 day')->>'id')::uuid;
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select v from cp where k='two'),'role','authenticated')::text,true);
set role authenticated;
select test.must_fail($$select career_assessment((select v from cp where k='attempt'),'{"action":"START"}')$$,'another candidate cannot start an attempt','NOT_FOUND');
reset role;
select set_config('request.jwt.claims',jsonb_build_object('sub',(select v from cp where k='one'),'role','authenticated')::text,true);
set role authenticated;
select test.check(not (career_assessment((select v from cp where k='attempt'),'{"action":"START"}')::text like '%"correct"%'),'candidate never receives the answer key');
select test.must_fail($$select career_assessment((select v from cp where k='attempt'),'{"action":"SAVE","version":1,"answers":{"0":1}}')$$,'stale answer writes refused','CONFLICT');
select career_assessment((select v from cp where k='attempt'),jsonb_build_object('action','SAVE','version',(career_assessment((select v from cp where k='attempt'))->>'version')::integer,'answers','{"0":1}'::jsonb));
select test.check(career_assessment((select v from cp where k='attempt'))#>>'{answers,0}'='1','saved answer survives reopening');
select career_assessment((select v from cp where k='attempt'),jsonb_build_object('action','SUBMIT','version',(career_assessment((select v from cp where k='attempt'))->>'version')::integer,'answers','{"0":1}'::jsonb));
select test.check((career_assessment((select v from cp where k='attempt'))->>'passed')::boolean,'score is calculated server-side');
select test.check(career_assessment((select v from cp where k='attempt'),'{"action":"SUBMIT","version":1,"answers":{}}')->>'score'='1','submit retry cannot alter a finalized result');
reset role;
select test.check((select stage='ASSESSMENT' from career_applications where id=(select v from cp where k='app')),'passing does not select or activate the candidate');
select test.login('hr_head');
set role authenticated;
select test.must_fail($$select hr_career_stage((select v from cp where k='app'),'SELECTED',2,null)$$,'interview stages cannot be skipped','CONFLICT');
select hr_career_stage((select v from cp where k='app'),'INTERVIEW',2,'Your assessment passed. Interview details will follow.');
select test.must_fail($$select hr_career_stage((select v from cp where k='app'),'SELECTED',3,null)$$,'selection requires both interview outcomes','Complete the HR');
select hr_career_interview((select v from cp where k='app'),jsonb_build_object('round','HR','scheduled_at',now()-interval '1 hour','location','Office reception'));
reset role;
select test.check(not exists(select 1 from profiles where id=(select v from cp where k='one')),'assessment success grants no staff profile');
rollback;
